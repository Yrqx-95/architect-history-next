import fs from 'node:fs'
import path from 'node:path'

import { fetchAll, ROOT } from './supabase-script-utils.ts'
import { flattenLocalizedAliases } from './lib/building-function-taxonomy.mjs'

const OUTPUT_JSON = path.join(ROOT, 'db/review-packets/graduation-unification-batch-001.json')
const APPLY_SQL = path.join(ROOT, 'db/manual-operations/graduation-unification-batch-001-apply.sql')
const ROLLBACK_SQL = path.join(ROOT, 'db/manual-operations/graduation-unification-batch-001-rollback.sql')

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, relativePath), 'utf8'))
}

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlNullable(value) {
  return value === null || value === undefined || value === '' ? 'NULL' : sqlText(value)
}

function sqlTextArray(values) {
  if (!values?.length) return "'{}'::text[]"
  return `ARRAY[${values.map(sqlText).join(', ')}]::text[]`
}

function refuseReviewedOutputOverwrite() {
  if (process.env.ALLOW_REVIEW_OUTPUT_OVERWRITE === '1') return
  const existing = [OUTPUT_JSON, APPLY_SQL, ROLLBACK_SQL].filter(filePath => fs.existsSync(filePath))
  if (!existing.length) return
  throw new Error(
    `Refusing to overwrite reviewed batch outputs: ${existing.map(filePath => path.relative(ROOT, filePath)).join(', ')}`,
  )
}

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

function buildApplySql(pack) {
  const profileValues = pack.profiles.map(profile => `  (
    ${sqlText(profile.case_id)}, ${sqlText(profile.building_id)}::uuid, ${sqlText(profile.building_slug)},
    ${sqlText(profile.concept_zh)}, ${sqlNullable(profile.concept_zh_hant)}, ${sqlNullable(profile.concept_en)}, ${sqlNullable(profile.concept_ja)},
    ${sqlTextArray(profile.keywords_zh)}, ${sqlTextArray(profile.keywords_zh_hant)}, ${sqlTextArray(profile.keywords_en)}, ${sqlTextArray(profile.keywords_ja)},
    ${sqlNullable(profile.plan_url)}, ${sqlNullable(profile.section_url)}, ${sqlText(profile.source_url)}, ${sqlText(profile.publication_status)}
  )`).join(',\n')

  const functionValues = pack.functions.map(item => `  (
    ${sqlText(item.slug)}, ${sqlNullable(item.broad_type_slug)},
    ${sqlText(item.names.zh)}, ${sqlText(item.names['zh-Hant'])}, ${sqlText(item.names.en)}, ${sqlText(item.names.ja)}
  )`).join(',\n')

  const aliasValues = pack.aliases.map(item =>
    `  (${sqlText(item.function_slug)}, ${sqlText(item.locale)}, ${sqlText(item.alias)})`,
  ).join(',\n')

  const assignmentValues = pack.assignments.map(item => `  (
    ${sqlText(item.building_id)}::uuid, ${sqlText(item.building_slug)}, ${sqlText(item.function_slug)},
    ${item.confidence}, ${sqlText(item.evidence_url)}, ${sqlText(item.evidence_note)}, ${sqlText(item.reviewed_at)}::timestamptz
  )`).join(',\n')

  return `-- Graduation unification batch 001: reviewed schema seed data.
-- Generated by scripts/prepare-graduation-unification-batch-001.mjs.
-- Prerequisite: reviewed graduation-unification foundation schema.
-- Scope: ${pack.counts.profiles} profiles, ${pack.counts.functions} functions,
-- ${pack.counts.aliases} aliases, ${pack.counts.assignments} approved assignments.
-- This operation does not update or delete canonical buildings or images.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.graduation_case_profiles') IS NULL
    OR to_regclass('public.building_functions') IS NULL
    OR to_regclass('public.building_function_aliases') IS NULL
    OR to_regclass('public.building_function_assignments') IS NULL THEN
    RAISE EXCEPTION 'Graduation unification schema prerequisite is missing';
  END IF;
END $$;

CREATE TEMP TABLE graduation_profile_seed (
  case_id text PRIMARY KEY,
  building_id uuid NOT NULL UNIQUE,
  building_slug text NOT NULL UNIQUE,
  concept_zh text NOT NULL,
  concept_zh_hant text,
  concept_en text,
  concept_ja text,
  keywords_zh text[] NOT NULL,
  keywords_zh_hant text[] NOT NULL,
  keywords_en text[] NOT NULL,
  keywords_ja text[] NOT NULL,
  plan_url text,
  section_url text,
  source_url text NOT NULL,
  publication_status text NOT NULL
) ON COMMIT DROP;

INSERT INTO graduation_profile_seed VALUES
${profileValues};

CREATE TEMP TABLE building_function_seed (
  slug text PRIMARY KEY,
  broad_type_slug text,
  name_zh text NOT NULL,
  name_zh_hant text NOT NULL,
  name_en text NOT NULL,
  name_ja text NOT NULL
) ON COMMIT DROP;

INSERT INTO building_function_seed VALUES
${functionValues};

CREATE TEMP TABLE building_function_alias_seed (
  function_slug text NOT NULL,
  locale text NOT NULL,
  alias text NOT NULL,
  PRIMARY KEY (locale, alias)
) ON COMMIT DROP;

INSERT INTO building_function_alias_seed VALUES
${aliasValues};

CREATE TEMP TABLE building_function_assignment_seed (
  building_id uuid NOT NULL,
  building_slug text NOT NULL,
  function_slug text NOT NULL,
  confidence numeric(4,3) NOT NULL,
  evidence_url text NOT NULL,
  evidence_note text NOT NULL,
  reviewed_at timestamptz NOT NULL,
  PRIMARY KEY (building_id, function_slug)
) ON COMMIT DROP;

INSERT INTO building_function_assignment_seed VALUES
${assignmentValues};

DO $$
DECLARE
  profile_seed_count integer;
  function_seed_count integer;
  alias_seed_count integer;
  assignment_seed_count integer;
  matched_profile_buildings integer;
  matched_assignment_rows integer;
  known_broad_types integer;
  existing_conflicts integer;
BEGIN
  SELECT count(*) INTO profile_seed_count FROM graduation_profile_seed;
  SELECT count(*) INTO function_seed_count FROM building_function_seed;
  SELECT count(*) INTO alias_seed_count FROM building_function_alias_seed;
  SELECT count(*) INTO assignment_seed_count FROM building_function_assignment_seed;

  IF profile_seed_count <> ${pack.counts.profiles}
    OR function_seed_count <> ${pack.counts.functions}
    OR alias_seed_count <> ${pack.counts.aliases}
    OR assignment_seed_count <> ${pack.counts.assignments} THEN
    RAISE EXCEPTION 'Seed count mismatch: profiles %, functions %, aliases %, assignments %',
      profile_seed_count, function_seed_count, alias_seed_count, assignment_seed_count;
  END IF;

  SELECT count(*) INTO matched_profile_buildings
  FROM graduation_profile_seed seed
  JOIN public.buildings building
    ON building.id = seed.building_id AND building.slug = seed.building_slug;

  SELECT count(*) INTO matched_assignment_rows
  FROM building_function_assignment_seed seed
  JOIN public.buildings building
    ON building.id = seed.building_id AND building.slug = seed.building_slug;

  SELECT count(*) INTO known_broad_types
  FROM building_function_seed seed
  JOIN public.building_types type ON type.slug = seed.broad_type_slug;

  IF matched_profile_buildings <> ${pack.counts.profiles}
    OR matched_assignment_rows <> ${pack.counts.assignments}
    OR known_broad_types <> ${pack.counts.functions} THEN
    RAISE EXCEPTION 'Canonical reference mismatch: profiles %, assignments %, broad types %',
      matched_profile_buildings, matched_assignment_rows, known_broad_types;
  END IF;

  SELECT
    (SELECT count(*) FROM public.graduation_case_profiles target JOIN graduation_profile_seed seed USING (case_id))
    + (SELECT count(*) FROM public.building_functions target JOIN building_function_seed seed USING (slug))
    + (SELECT count(*) FROM public.building_function_aliases target JOIN building_function_alias_seed seed USING (function_slug, locale, alias))
    + (SELECT count(*) FROM public.building_function_assignments target JOIN building_function_assignment_seed seed USING (building_id, function_slug))
  INTO existing_conflicts;

  IF existing_conflicts <> 0 THEN
    RAISE EXCEPTION 'Batch 001 requires an empty target for its keys; found % conflicts', existing_conflicts;
  END IF;
END $$;

INSERT INTO public.building_functions (
  slug, broad_type_slug, name_zh, name_zh_hant, name_en, name_ja
)
SELECT slug, broad_type_slug, name_zh, name_zh_hant, name_en, name_ja
FROM building_function_seed;

INSERT INTO public.building_function_aliases (function_slug, locale, alias)
SELECT function_slug, locale, alias
FROM building_function_alias_seed;

INSERT INTO public.graduation_case_profiles (
  case_id, building_id,
  concept_zh, concept_zh_hant, concept_en, concept_ja,
  keywords_zh, keywords_zh_hant, keywords_en, keywords_ja,
  plan_url, section_url, source_url, publication_status
)
SELECT
  case_id, building_id,
  concept_zh, concept_zh_hant, concept_en, concept_ja,
  keywords_zh, keywords_zh_hant, keywords_en, keywords_ja,
  plan_url, section_url, source_url, publication_status
FROM graduation_profile_seed;

INSERT INTO public.building_function_assignments (
  building_id, function_slug, is_primary, confidence, review_status,
  assignment_method, evidence_url, evidence_note, reviewed_at
)
SELECT
  building_id, function_slug, false, confidence, 'approved',
  'source-derived', evidence_url, evidence_note, reviewed_at
FROM building_function_assignment_seed;

DO $$
DECLARE
  written_profiles integer;
  written_functions integer;
  written_aliases integer;
  written_assignments integer;
BEGIN
  SELECT count(*) INTO written_profiles
  FROM public.graduation_case_profiles target JOIN graduation_profile_seed seed USING (case_id, building_id);
  SELECT count(*) INTO written_functions
  FROM public.building_functions target JOIN building_function_seed seed USING (slug);
  SELECT count(*) INTO written_aliases
  FROM public.building_function_aliases target JOIN building_function_alias_seed seed USING (function_slug, locale, alias);
  SELECT count(*) INTO written_assignments
  FROM public.building_function_assignments target JOIN building_function_assignment_seed seed USING (building_id, function_slug)
  WHERE target.review_status = 'approved';

  IF written_profiles <> ${pack.counts.profiles}
    OR written_functions <> ${pack.counts.functions}
    OR written_aliases <> ${pack.counts.aliases}
    OR written_assignments <> ${pack.counts.assignments} THEN
    RAISE EXCEPTION 'Post-write count mismatch: profiles %, functions %, aliases %, assignments %',
      written_profiles, written_functions, written_aliases, written_assignments;
  END IF;
END $$;

COMMIT;
`
}

function buildRollbackSql(pack) {
  const profileValues = pack.profiles
    .map(item => `  (${sqlText(item.case_id)}, ${sqlText(item.building_id)}::uuid)`)
    .join(',\n')
  const assignmentValues = pack.assignments
    .map(item => `  (${sqlText(item.building_id)}::uuid, ${sqlText(item.function_slug)})`)
    .join(',\n')
  const aliasValues = pack.aliases
    .map(item => `  (${sqlText(item.function_slug)}, ${sqlText(item.locale)}, ${sqlText(item.alias)})`)
    .join(',\n')
  const functionValues = pack.functions.map(item => `  (${sqlText(item.slug)})`).join(',\n')

  return `-- Rollback graduation unification batch 001 seed data only.
-- Does not drop the foundation schema or touch canonical buildings/images.

BEGIN;

CREATE TEMP TABLE graduation_profile_rollback (case_id text PRIMARY KEY, building_id uuid NOT NULL UNIQUE) ON COMMIT DROP;
INSERT INTO graduation_profile_rollback VALUES
${profileValues};

CREATE TEMP TABLE building_function_assignment_rollback (building_id uuid NOT NULL, function_slug text NOT NULL, PRIMARY KEY (building_id, function_slug)) ON COMMIT DROP;
INSERT INTO building_function_assignment_rollback VALUES
${assignmentValues};

CREATE TEMP TABLE building_function_alias_rollback (function_slug text NOT NULL, locale text NOT NULL, alias text NOT NULL, PRIMARY KEY (locale, alias)) ON COMMIT DROP;
INSERT INTO building_function_alias_rollback VALUES
${aliasValues};

CREATE TEMP TABLE building_function_rollback (slug text PRIMARY KEY) ON COMMIT DROP;
INSERT INTO building_function_rollback VALUES
${functionValues};

DO $$
DECLARE
  unexpected_function_references integer;
BEGIN
  SELECT count(*) INTO unexpected_function_references
  FROM public.building_function_assignments assignment
  JOIN building_function_rollback function ON function.slug = assignment.function_slug
  LEFT JOIN building_function_assignment_rollback expected
    ON expected.building_id = assignment.building_id AND expected.function_slug = assignment.function_slug
  WHERE expected.building_id IS NULL;

  IF unexpected_function_references <> 0 THEN
    RAISE EXCEPTION 'Refusing function rollback: found % assignments outside batch 001', unexpected_function_references;
  END IF;
END $$;

DELETE FROM public.building_function_assignments target
USING building_function_assignment_rollback seed
WHERE target.building_id = seed.building_id
  AND target.function_slug = seed.function_slug
  AND target.review_status = 'approved';

DELETE FROM public.graduation_case_profiles target
USING graduation_profile_rollback seed
WHERE target.case_id = seed.case_id
  AND target.building_id = seed.building_id;

DELETE FROM public.building_function_aliases target
USING building_function_alias_rollback seed
WHERE target.function_slug = seed.function_slug
  AND target.locale = seed.locale
  AND target.alias = seed.alias;

DELETE FROM public.building_functions target
USING building_function_rollback seed
WHERE target.slug = seed.slug;

COMMIT;
`
}

refuseReviewedOutputOverwrite()

const exactDecisions = readJson('db/review-decisions/graduation-building-links-001.json')
const fuzzyDecisions = readJson('db/review-decisions/graduation-building-links-002.json')
const functionDecisions = readJson('db/review-decisions/building-function-library-001.json')
const taxonomy = readJson('db/taxonomies/building-functions-v1.json')
const cases = readJson('public/data/graduation/cases.json')
const buildings = await fetchAll('buildings')

const buildingsBySlug = new Map(buildings.map(building => [building.slug, building]))
const casesById = new Map(cases.map(item => [item.id, item]))
const approvedCaseLinks = [...exactDecisions.decisions, ...fuzzyDecisions.decisions]
  .filter(item => item.decision === 'approved')

assert(approvedCaseLinks.length === 21, `Expected 21 approved CASE links, found ${approvedCaseLinks.length}`)
assert(new Set(approvedCaseLinks.map(item => item.case_id)).size === 21, 'Approved CASE IDs are not unique')
assert(new Set(approvedCaseLinks.map(item => item.building_slug)).size === 21, 'Approved CASE building slugs are not unique')

const profiles = approvedCaseLinks.map(link => {
  const building = buildingsBySlug.get(link.building_slug)
  const item = casesById.get(link.case_id)
  assert(building, `Missing canonical building for ${link.case_id}: ${link.building_slug}`)
  assert(item, `Missing graduation case ${link.case_id}`)
  assert(item.status === 'published', `${link.case_id} is not published`)
  assert(item.concept && item.source_url && item.keywords?.length, `${link.case_id} lacks required profile data`)
  return {
    case_id: item.id,
    building_id: building.id,
    building_slug: building.slug,
    concept_zh: item.concept,
    concept_zh_hant: null,
    concept_en: item.concept_en || null,
    concept_ja: item.concept_ja || null,
    keywords_zh: item.keywords,
    keywords_zh_hant: [],
    keywords_en: item.keywords_en || [],
    keywords_ja: item.keywords_ja || [],
    plan_url: item.plan_url || null,
    section_url: item.section_url || null,
    source_url: item.source_url,
    publication_status: item.status,
  }
})

const assignments = functionDecisions.decisions.flatMap(decision => {
  const building = buildingsBySlug.get(decision.building_slug)
  assert(building, `Missing function-decision building ${decision.building_slug}`)
  assert(building.id === decision.building_id, `UUID mismatch for ${decision.building_slug}`)
  assert(decision.decision === 'approved', `Unexpected non-approved function decision: ${decision.building_slug}`)
  return decision.approved_functions.map(functionSlug => ({
    building_id: building.id,
    building_slug: building.slug,
    function_slug: functionSlug,
    confidence: '1.000',
    evidence_url: decision.evidence.url,
    evidence_note: decision.evidence.claim,
    reviewed_at: '2026-07-12T00:00:00Z',
  }))
})

assert(assignments.length === 23, `Expected 23 approved function assignments, found ${assignments.length}`)
assert(new Set(assignments.map(item => `${item.building_id}:${item.function_slug}`)).size === 23, 'Duplicate function assignments')

const aliases = flattenLocalizedAliases(taxonomy)
const pack = {
  schema_version: 1,
  batch_id: 'graduation-unification-batch-001',
  generated_at: new Date().toISOString(),
  mode: 'reviewed-dry-run-output-no-database-write',
  prerequisites: [
    'graduation-unification foundation schema is applied',
    'all four target tables contain no conflicting batch keys',
    'canonical building UUID and slug pairs still match this pack',
  ],
  counts: {
    profiles: profiles.length,
    functions: taxonomy.functions.length,
    aliases: aliases.length,
    assignments: assignments.length,
  },
  profiles,
  functions: taxonomy.functions,
  aliases,
  assignments,
}

fs.mkdirSync(path.dirname(OUTPUT_JSON), { recursive: true })
fs.mkdirSync(path.dirname(APPLY_SQL), { recursive: true })
fs.writeFileSync(OUTPUT_JSON, `${JSON.stringify(pack, null, 2)}\n`)
fs.writeFileSync(APPLY_SQL, buildApplySql(pack))
fs.writeFileSync(ROLLBACK_SQL, buildRollbackSql(pack))

